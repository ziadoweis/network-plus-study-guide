// Build: node tools/build.mjs  →  dist/ (deploy this folder)
// Splits the app into an entry chunk plus lazy chunks (quizzes, labs, Packet Tracer),
// minifies with esbuild, fingerprints file names for immutable caching, inlines the CSS,
// and generates the service worker precache list and Netlify headers.
import {createRequire} from 'node:module';
import {readFileSync,writeFileSync,mkdirSync,rmSync,readdirSync,copyFileSync,statSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {gzipSync,brotliCompressSync,constants} from 'node:zlib';
import {createHash} from 'node:crypto';

const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const req=createRequire(join(root,'package.json'));
let esbuild;
try{esbuild=req('esbuild')}catch{esbuild=createRequire('/opt/npm-tools/node_modules/')('esbuild')}
const src=p=>join(root,'src',p),dist=p=>join(root,'dist',p);

await import('./gen-meta.mjs');

rmSync(dist(''),{recursive:true,force:true});
mkdirSync(dist('assets'),{recursive:true});

const r=await esbuild.build({
  entryPoints:{app:src('js/app.js')},bundle:true,splitting:true,format:'esm',minify:true,
  target:['es2020'],outdir:dist('assets'),
  entryNames:'[name]-[hash]',chunkNames:'[name]-[hash]',metafile:true,legalComments:'none',charset:'utf8',write:true,logLevel:'warning'});

const outs=r.metafile.outputs;
const entry=Object.keys(outs).find(k=>outs[k].entryPoint);
const entryName=entry.split('/').pop();
const preload=outs[entry].imports.filter(i=>i.kind==='import-statement').map(i=>`<link rel="modulepreload" href="./assets/${i.path.split('/').pop()}">`).join('\n');

const css=(await esbuild.transform(readFileSync(src('style.css'),'utf8'),{loader:'css',minify:true})).code.trim();
const html=readFileSync(src('index.html'),'utf8')
  .replace('<!--@PRELOAD@-->',preload).replace('/*@CSS@*/',css).replace('<!--@ENTRY@-->',entryName)
  .replace(/\n\s*\n/g,'\n');
writeFileSync(dist('index.html'),html);

for(const f of readdirSync(src('static')))copyFileSync(src('static/'+f),dist(f));

writeFileSync(dist('manifest.webmanifest'),JSON.stringify({
  name:'Network+ Study Guide',short_name:'Net+ Guide',description:'CompTIA Network+ N10-009 quizzes, labs and Packet Tracer labs',
  start_url:'./',scope:'./',display:'standalone',background_color:'#121417',theme_color:'#121417',
  icons:[{src:'icon-192.png',sizes:'192x192',type:'image/png'},{src:'icon-512.png',sizes:'512x512',type:'image/png'},{src:'icon-maskable-512.png',sizes:'512x512',type:'image/png',purpose:'maskable'},{src:'favicon.svg',sizes:'any',type:'image/svg+xml'}]}));

const assets=readdirSync(dist('assets')).map(f=>'assets/'+f);
const precache=['./','manifest.webmanifest','favicon.svg','icon-192.png',...assets];
const version=createHash('sha256').update(html+assets.join()).digest('hex').slice(0,10);
writeFileSync(dist('sw.js'),`// Generated by tools/build.mjs
const CACHE='np-${version}';
const PRECACHE=${JSON.stringify(precache)};
self.addEventListener('install',e=>{e.waitUntil(caches.open(CACHE).then(c=>c.addAll(PRECACHE)).then(()=>self.skipWaiting()))});
self.addEventListener('activate',e=>{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim()))});
self.addEventListener('fetch',e=>{
  const r=e.request;if(r.method!=='GET')return;
  const u=new URL(r.url);if(u.origin!==location.origin)return;
  if(r.mode==='navigate'){
    // Network first for the page itself so updates show up; fall back to the cached copy offline.
    e.respondWith(fetch(r).then(res=>{const c=res.clone();caches.open(CACHE).then(x=>x.put('./',c));return res}).catch(()=>caches.match('./')));
    return;
  }
  // Fingerprinted assets never change: cache first.
  e.respondWith(caches.match(r).then(m=>m||fetch(r).then(res=>{if(res.ok&&u.pathname.includes('/assets/')){const c=res.clone();caches.open(CACHE).then(x=>x.put(r,c))}return res})));
});
`);

writeFileSync(dist('_headers'),`/*
  Strict-Transport-Security: max-age=31536000
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'; manifest-src 'self'; worker-src 'self'; object-src 'none'; base-uri 'self'; form-action 'none'; frame-ancestors 'none'

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/sw.js
  Cache-Control: no-cache

/manifest.webmanifest
  Cache-Control: public, max-age=86400
`);

// Size report
const rows=[];const walk=d=>{for(const f of readdirSync(dist(d))){const p=join(d,f);if(statSync(dist(p)).isDirectory())walk(p);else{const b=readFileSync(dist(p));rows.push([p,b.length,gzipSync(b,{level:9}).length,brotliCompressSync(b,{params:{[constants.BROTLI_PARAM_QUALITY]:11}}).length])}}};
walk('');
const kb=n=>(n/1024).toFixed(1).padStart(7)+' KB';
console.log('file'.padEnd(36),'   raw','      gzip','    brotli');
for(const [p,a,g,b] of rows.sort((x,y)=>y[1]-x[1]))console.log(p.padEnd(36),kb(a),kb(g),kb(b));
const first=rows.filter(([p])=>p==='index.html'||p==='assets/'+entryName||preload.includes(p.split('/').pop()));
console.log('\nFirst load (HTML + entry + preloaded chunks), brotli:',kb(first.reduce((s,r)=>s+r[3],0)));
