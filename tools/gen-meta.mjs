// Extracts the lightweight Packet Tracer lab index (no lab bodies) so the shell can list labs without loading them.
import {writeFileSync} from 'node:fs';
const {PTLABS}=await import(new URL('../src/js/pt-data.js',import.meta.url));
const meta=PTLABS.map(({slug,title,obj,time,goal})=>({slug,title,obj,time,goal}));
writeFileSync(new URL('../src/js/pt-meta.js',import.meta.url),'// Generated by tools/gen-meta.mjs from pt-data.js. Do not edit.\nexport const PT_META='+JSON.stringify(meta)+';\n');
console.log('pt-meta:',meta.length,'labs');
