// Extracts the lightweight Packet Tracer lab index (no lab bodies) so the shell can list labs without loading them.
import {writeFileSync} from 'node:fs';
const {PTLABS}=await import(new URL('../src/js/pt-data.js',import.meta.url));
const meta=PTLABS.map(({slug,title,obj,time,goal})=>({slug,title,obj,time,goal}));
writeFileSync(new URL('../src/js/pt-meta.js',import.meta.url),'// Generated by tools/gen-meta.mjs from pt-data.js. Do not edit.\nexport const PT_META='+JSON.stringify(meta)+';\n');
console.log('pt-meta:',meta.length,'labs');

// Lesson index (titles, objectives, reading time) so the shell and study path can list lessons without loading their text.
const parts=await Promise.all([1,2,3,4].map(i=>import(new URL(`../src/js/lessons/part${i}.js`,import.meta.url))));
const lessons=parts.flatMap((p,i)=>p.LESSONS.map(l=>{
  const words=(l.intro+' '+l.html).replace(/<[^>]+>/g,' ').split(/\s+/).filter(Boolean).length;
  return {n:l.n,part:i+1,title:l.title,obj:l.obj,book:l.book,intro:l.intro,min:Math.ceil(words/90/5)*5};
})).sort((a,b)=>a.n-b.n);
writeFileSync(new URL('../src/js/lesson-meta.js',import.meta.url),'// Generated by tools/gen-meta.mjs from lessons/part*.js. Do not edit.\nexport const LESSON_META='+JSON.stringify(lessons)+';\n');
console.log('lesson-meta:',lessons.map(l=>`${l.n}:${l.min}m`).join(' '));
